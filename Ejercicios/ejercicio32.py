#Recuerda que el area A de un triangulo se puede calcular a partir de la base b y la altura h

print("Calculo del area de un triangulo")

base=float(input("Ingrese el valor base: "))
altura=float(input("Ingrese el valor altura: "))

area=(base*altura)/2

print("El area del triangulo es: ", area)
